export function loadBlogPosts(): BlogPost[] {
  if (typeof window === 'undefined') return INITIAL_BLOG_POSTS
  try {
    const raw = localStorage.getItem(BLOG_STORAGE_KEY)
    if (!raw) return INITIAL_BLOG_POSTS
    const parsed = JSON.parse(raw) as BlogPost[]
    return Array.isArray(parsed) && parsed.length > 0 ? parsed : INITIAL_BLOG_POSTS
  } catch {
    return INITIAL_BLOG_POSTS
  }
}

export function saveBlogPosts(posts: BlogPost[]): void {
  if (typeof window === 'undefined') return
  try {
    localStorage.setItem(BLOG_STORAGE_KEY, JSON.stringify(posts))
  } catch {
    // localStorage quota exceeded or unavailable
  }
}

export function ensureUniqueSlug(
  slug: string,
  existingPosts: BlogPost[],
  excludeId?: string
): string {
  const taken = new Set(
    existingPosts.filter((p) => p.id !== excludeId).map((p) => p.slug)
  )
  if (!taken.has(slug)) return slug
  let counter = 2
  while (taken.has(`${slug}-${counter}`)) counter++
  return `${slug}-${counter}`
}

export function generateSlug(title: string): string {
  const ascii = title
    .toLowerCase()
    .replace(/[^\x00-\x7F]/g, '') // remove non-ASCII (Bengali chars)
    .replace(/[^a-z0-9\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
  if (ascii.length >= 4) return ascii
  // Fallback: use timestamp when title is entirely non-ASCII
  return 'post-' + Date.now().toString(36)
}

export function generateId(): string {
  return 'post-' + Date.now().toString(36) + '-' + Math.random().toString(36).slice(2, 7)
}

export function estimateReadTime(content: string): number {
  const text = content.replace(/<[^>]+>/g, ' ')
  const words = text.trim().split(/\s+/).filter(Boolean).length
  const minutes = Math.round(words / 200)
  return Math.max(1, minutes)
}
